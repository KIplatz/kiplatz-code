_RAND = "A-Za-z0-9\u00c0-\u024f\u0370-\u03ff\u0400-\u04ff"
_MUSTER = re.compile(rf"(?<![{_RAND}])(" + "|".join(re.escape(n) for n in NAMEN) + rf")(?![{_RAND}])")


def erkennen(text: str) -> str | None:
    m = _MUSTER.search(text or "")
    return NAMEN.get(m.group(1)) if m else None


def alle(text: str) -> set[str]:
    return {NAMEN[m.group(1)] for m in _MUSTER.finditer(text or "")}
